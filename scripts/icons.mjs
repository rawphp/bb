// Renders the app icons, the iOS launch images, the web app manifest and the
// head tags that name them (PWA-001, PWA-002) from resources/icons/mark.svg and
// the design tokens. No browser: @resvg/resvg-js renders the SVG.
// Run `npm run icons` after changing the mark or the tokens, and commit the output.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const NAME = 'Bodybuilder';

// Portrait CSS size and pixel ratio of each iPhone iOS 17.4 runs on, newest first.
export const SCREENS = [
    { width: 440, height: 956, ratio: 3 }, // 16 Pro Max, 17 Pro Max
    { width: 430, height: 932, ratio: 3 }, // 14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus
    { width: 420, height: 912, ratio: 3 }, // Air
    { width: 402, height: 874, ratio: 3 }, // 16 Pro, 17, 17 Pro
    { width: 393, height: 852, ratio: 3 }, // 14 Pro, 15, 15 Pro, 16
    { width: 390, height: 844, ratio: 3 }, // 12, 13, 14, 16e
    { width: 428, height: 926, ratio: 3 }, // 12 Pro Max, 13 Pro Max, 14 Plus
    { width: 375, height: 812, ratio: 3 }, // XS, 11 Pro, 12 mini, 13 mini
    { width: 414, height: 896, ratio: 3 }, // XS Max, 11 Pro Max
    { width: 414, height: 896, ratio: 2 }, // XR, 11
    { width: 375, height: 667, ratio: 2 }, // SE (2nd and 3rd generation)
];

export const ICONS = [
    { file: 'icon-192.png', size: 192, purpose: 'any' },
    { file: 'icon-512.png', size: 512, purpose: 'any' },
    { file: 'maskable-192.png', size: 192, purpose: 'maskable' },
    { file: 'maskable-512.png', size: 512, purpose: 'maskable' },
];

export const APPLE_TOUCH_ICON = { file: 'apple-touch-icon.png', size: 180 };

// The light and dark values of a light-dark() token in tokens.css.
export function token(css, name) {
    const match = new RegExp(`--bb-${name}:\\s*light-dark\\((#[0-9a-f]{6}),\\s*(#[0-9a-f]{6})\\)`, 'i').exec(css);
    if (!match) throw new Error(`tokens.css has no light-dark() --bb-${name}`);

    return { light: match[1], dark: match[2] };
}

export function launchFile({ width, height, ratio }, scheme) {
    return `${width * ratio}x${height * ratio}-${scheme}.png`;
}

export function launchMedia({ width, height, ratio }, scheme) {
    return `(device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait) and (prefers-color-scheme: ${scheme})`;
}

function markShapes() {
    const svg = readFileSync(join(root, 'resources/icons/mark.svg'), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
    const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg);
    if (!inner) throw new Error('resources/icons/mark.svg has no <svg> element');

    return inner[1];
}

// The mark on the accent, on a 512 grid. Rounded for "any"; full bleed where the
// platform crops it (maskable, apple-touch-icon).
function iconSvg(mark, accent, rounded) {
    return `<rect width="512" height="512" rx="${rounded ? 112 : 0}" fill="${accent}"/>${mark}`;
}

function png(svg, width, height) {
    const doc = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">${svg}</svg>`;

    return new Resvg(doc, { fitTo: { mode: 'original' } }).render().asPng();
}

function scaled(svg, size, x = 0, y = 0) {
    return `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="0 0 512 512">${svg}</svg>`;
}

export function manifest(background) {
    return {
        id: '/',
        name: NAME,
        short_name: NAME,
        start_url: '/',
        scope: '/',
        display: 'standalone',
        orientation: 'portrait',
        theme_color: background.light,
        background_color: background.light,
        icons: ICONS.map(({ file, size, purpose }) => ({ src: `/icons/${file}`, sizes: `${size}x${size}`, type: 'image/png', purpose })),
    };
}

export function headTags(background) {
    const lines = [
        '{{-- Generated by scripts/icons.mjs (PWA-001, PWA-002). Run `npm run icons`; do not edit. --}}',
        '<link rel="manifest" href="/manifest.webmanifest">',
        `<meta name="theme-color" media="(prefers-color-scheme: light)" content="${background.light}">`,
        `<meta name="theme-color" media="(prefers-color-scheme: dark)" content="${background.dark}">`,
        '<meta name="mobile-web-app-capable" content="yes">',
        '<meta name="apple-mobile-web-app-capable" content="yes">',
        // "default" is a light bar on a light page and a dark bar on a dark one.
        '<meta name="apple-mobile-web-app-status-bar-style" content="default">',
        `<meta name="apple-mobile-web-app-title" content="${NAME}">`,
        `<link rel="apple-touch-icon" href="/icons/${APPLE_TOUCH_ICON.file}">`,
    ];
    for (const screen of SCREENS) {
        for (const scheme of ['light', 'dark']) {
            lines.push(`<link rel="apple-touch-startup-image" media="${launchMedia(screen, scheme)}" href="/icons/launch/${launchFile(screen, scheme)}">`);
        }
    }

    return `${lines.join('\n')}\n`;
}

function main() {
    const css = readFileSync(join(root, 'resources/js/design/tokens.css'), 'utf8');
    const background = token(css, 'background');
    const accent = token(css, 'accent').light;
    const mark = markShapes();
    const icons = join(root, 'public/icons');

    rmSync(icons, { recursive: true, force: true });
    mkdirSync(join(icons, 'launch'), { recursive: true });

    for (const { file, size, purpose } of ICONS) {
        writeFileSync(join(icons, file), png(scaled(iconSvg(mark, accent, purpose === 'any'), size), size, size));
    }
    const touch = APPLE_TOUCH_ICON.size;
    writeFileSync(join(icons, APPLE_TOUCH_ICON.file), png(scaled(iconSvg(mark, accent, false), touch), touch, touch));

    // A launch image is the page background with the rounded icon in the middle, 128 points wide.
    for (const screen of SCREENS) {
        const width = screen.width * screen.ratio;
        const height = screen.height * screen.ratio;
        const size = 128 * screen.ratio;
        const icon = scaled(iconSvg(mark, accent, true), size, (width - size) / 2, (height - size) / 2);
        for (const scheme of ['light', 'dark']) {
            const svg = `<rect width="${width}" height="${height}" fill="${background[scheme]}"/>${icon}`;
            writeFileSync(join(icons, 'launch', launchFile(screen, scheme)), png(svg, width, height));
        }
    }

    writeFileSync(join(root, 'public/manifest.webmanifest'), `${JSON.stringify(manifest(background), null, 4)}\n`);
    writeFileSync(join(root, 'resources/views/pwa.blade.php'), headTags(background));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
