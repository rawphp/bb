// npm run contracts: generate resources/js/contracts/<name>.ts from the schema
// snapshots in tests/fixtures/schemas/<name>.input.json and <name>.output.json.
// The output is committed; a Vitest test fails when it is stale.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const SCHEMAS = 'tests/fixtures/schemas';
const CONTRACTS = 'resources/js/contracts';
const BANNER = '// Generated by `npm run contracts` from tests/fixtures/schemas/. Do not edit.\n';

const studly = (name) => name.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// PHP encodes an empty `properties` map as a list.
function normalise(schema) {
    if (Array.isArray(schema)) return schema.map(normalise);
    if (schema === null || typeof schema !== 'object') return schema;
    const out = {};
    for (const [key, value] of Object.entries(schema)) {
        if (key === '$schema') continue;
        out[key] = key === 'properties' && Array.isArray(value) && value.length === 0 ? {} : normalise(value);
    }
    return out;
}

/** @returns {Promise<Map<string, string>>} file name → TS source, sorted by name */
export async function generate(schemaDir = SCHEMAS) {
    const sides = new Map();
    for (const file of readdirSync(schemaDir).sort()) {
        const match = /^([a-z0-9_]+)\.(input|output)\.json$/.exec(file);
        if (!match) continue;
        const [, name, side] = match;
        if (!sides.has(name)) sides.set(name, []);
        sides.get(name).push([side, JSON.parse(readFileSync(join(schemaDir, file), 'utf8'))]);
    }

    const files = new Map();
    for (const [name, list] of sides) {
        const parts = [];
        for (const [side, schema] of list) {
            const type = studly(name) + (side === 'input' ? 'Input' : 'Output');
            parts.push(await compile(normalise(schema), type, { bannerComment: '', additionalProperties: false, maxItems: -1 }));
        }
        files.set(`${name}.ts`, BANNER + '\n' + parts.join('\n'));
    }
    return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const files = await generate();
    mkdirSync(CONTRACTS, { recursive: true });
    for (const file of readdirSync(CONTRACTS)) {
        if (file.endsWith('.ts')) rmSync(join(CONTRACTS, file));
    }
    for (const [file, source] of files) writeFileSync(join(CONTRACTS, file), source);
    console.log(`Wrote ${files.size} contract file(s) to ${CONTRACTS}/`);
}
