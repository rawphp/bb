$rows = [];

foreach ($library as $muscleGroup => $lines) {
    foreach ($lines as $line) {
        [$name, $equipment, $sfr, $band, $flags] = array_pad(explode('|', $line), 5, '');

        $loadType = str_contains($flags, 'p') ? 'bodyweightPlusLoad' : $loadTypes[$equipment];

        $rows[] = [
            'name' => $name,
            'muscle_group' => $muscleGroup,
            'equipment' => $equipment,
            'load_type' => $loadType,
            'sfr_rating' => $sfr,
            'rep_range_min' => $bands[(int) $band][0],
            'rep_range_max' => $bands[(int) $band][1],
            'is_compound' => str_contains($flags, 'c'),
        ];
    }
}

return $rows;
